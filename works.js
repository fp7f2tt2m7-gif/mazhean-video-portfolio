const localVideoLibrary = window.localVideoLibrary || {};
const expandedWorkIds = new Set();

works.forEach((work) => {
  if (localVideoLibrary[work.id]?.length) {
    work.videos = localVideoLibrary[work.id];
  }
});

function getFeaturedWorks() {
  return works.filter((work) => work.featured).sort((a, b) => a.priority - b.priority);
}

function getCaseVideoCount(work) {
  return work.videos.length;
}

function createRoleTags(roles) {
  return roles.map((role) => `<span>${role}</span>`).join("");
}

function createVideoTypeTags(videos) {
  return [...new Set(videos.map((video) => video.type))]
    .map((type) => `<span>${type}</span>`)
    .join("");
}

function getVideoMeta(video) {
  return [video.type, video.format, video.size || video.duration].filter(Boolean);
}

function getPrimaryVideo(work) {
  return work.videos.find((video) => video.url) || work.videos[0];
}

function getSecondaryVideos(work) {
  const primaryVideo = getPrimaryVideo(work);
  return work.videos.filter((video) => video !== primaryVideo).slice(0, 3);
}

function escapeAttribute(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function getVideoAction(video) {
  if (!video.url) return `<span class="video-link pending" aria-disabled="true">待补充</span>`;
  const meta = getVideoMeta(video).join(" · ");
  return `
    <button
      class="video-link"
      type="button"
      data-video-src="${escapeAttribute(video.url)}"
      data-video-title="${escapeAttribute(video.title)}"
      data-video-meta="${escapeAttribute(meta)}"
    >
      播放
    </button>
  `;
}

function renderPreviewMedia(video, fallbackCover, label) {
  const cover = video?.poster || video?.cover || fallbackCover;
  if (!video?.url) return `<img src="${cover}" alt="${label}封面" loading="lazy">`;

  return `
    <video
      class="preview-media"
      data-preview-src="${escapeAttribute(video.url)}#t=0.1"
      poster="${escapeAttribute(cover)}"
      muted
      playsinline
      preload="none"
      aria-label="${escapeAttribute(label)}视频预览"
    ></video>
  `;
}

function updateOverview() {
  const statCount = document.querySelector("#stat-count");
  const statVideoCount = document.querySelector("#stat-video-count");
  if (statCount) statCount.textContent = getFeaturedWorks().length;
  if (statVideoCount) {
    statVideoCount.textContent = getFeaturedWorks().reduce((total, work) => total + work.videos.length, 0);
  }
}

function renderExperienceNav() {
  const grid = document.querySelector("#experience-grid");
  if (!grid) return;

  grid.innerHTML = getFeaturedWorks()
    .map((work, index) => `
      <article class="experience-card">
        <span>${String(index + 1).padStart(2, "0")}</span>
        <div>
          <p>${work.period}</p>
          <h3>${work.company}</h3>
          <strong>${work.title}</strong>
          <em>${work.position}｜${getCaseVideoCount(work)} 条案例视频</em>
        </div>
        <button type="button" data-work-id="${work.id}">查看作品</button>
      </article>
    `)
    .join("");

  grid.querySelectorAll("button").forEach((button) => {
    button.addEventListener("click", () => openWorkFromExperience(button.dataset.workId));
  });
}

function openWorkFromExperience(id) {
  expandedWorkIds.clear();
  expandedWorkIds.add(id);
  renderWorks();

  const target = document.querySelector(`[data-work-card="${id}"]`);
  if (target) {
    target.scrollIntoView({ behavior: "smooth", block: "start" });
  }
}

function renderVideos(work, videos) {
  if (!expandedWorkIds.has(work.id)) return "";
  if (!videos.length) return "";

  return `
    <div class="video-list" aria-label="${work.title}的延展案例列表">
      ${videos.map((video) => `
        <article class="video-card">
          <button
            class="video-thumb"
            type="button"
            data-video-src="${escapeAttribute(video.url)}"
            data-video-title="${escapeAttribute(video.title)}"
            data-video-meta="${escapeAttribute(getVideoMeta(video).join(" · "))}"
            aria-label="播放${escapeAttribute(video.title)}"
          >
            ${renderPreviewMedia(video, work.cover, video.title)}
          </button>
          <div class="video-info">
            <div class="video-meta">
              ${getVideoMeta(video).map((item) => `<span>${item}</span>`).join("")}
            </div>
            <h4>${video.title}</h4>
            ${getVideoAction(video)}
          </div>
        </article>
      `).join("")}
    </div>
  `;
}

function renderFeaturedVideo(work, video, secondaryCount) {
  const cover = video?.cover || work.cover;
  if (!video?.url) {
    return `
      <img src="${cover}" alt="${work.title}封面">
      <span class="video-count">视频待补充</span>
    `;
  }

  const meta = getVideoMeta(video).join(" · ");
  return `
    ${renderPreviewMedia(video, cover, video.title)}
    <button
      class="feature-video-button"
      type="button"
      data-video-src="${escapeAttribute(video.url)}"
      data-video-title="${escapeAttribute(video.title)}"
      data-video-meta="${escapeAttribute(meta)}"
      aria-label="播放${video.title}"
    >
      <span class="featured-video-label">主推案例</span>
      <span class="featured-video-title">${video.title}</span>
      <span class="featured-video-meta">${meta}</span>
      <span class="featured-play-label">播放主推视频</span>
      <span class="play-indicator large" aria-hidden="true"></span>
    </button>
    <span class="video-count">1 个主推 + ${secondaryCount} 个延展</span>
  `;
}

function renderWorks() {
  const grid = document.querySelector("#work-grid");
  if (!grid) return;

  grid.innerHTML = getFeaturedWorks()
    .map((work) => {
      const primaryVideo = getPrimaryVideo(work);
      const secondaryVideos = getSecondaryVideos(work);
      const isExpanded = expandedWorkIds.has(work.id);
      return `
        <article class="work-card ${isExpanded ? "expanded" : ""}" data-work-card="${work.id}">
          <div class="work-cover">
            ${renderFeaturedVideo(work, primaryVideo, secondaryVideos.length)}
          </div>
          <div class="work-body">
            <div class="work-kicker">
              <span>${work.period}</span>
              <span>${work.category}</span>
            </div>
            <h3>${work.title}</h3>
            <p class="company">${work.company}｜${work.position}</p>
            <div class="roles" aria-label="项目职责">${createRoleTags(work.roles)}</div>
            <p class="summary">${work.summary}</p>
            <p class="result">${work.result}</p>
            <div class="video-type-preview" aria-label="视频类型">${createVideoTypeTags(work.videos)}</div>
            ${secondaryVideos.length ? `
              <button class="expand-button" type="button" data-work-id="${work.id}" aria-expanded="${isExpanded}">
                ${isExpanded ? "收起延展案例" : `查看剩余 ${secondaryVideos.length} 条`}
              </button>
            ` : ""}
          </div>
          ${renderVideos(work, secondaryVideos)}
        </article>
      `;
    })
    .join("");

  grid.querySelectorAll(".expand-button").forEach((button) => {
    button.addEventListener("click", () => {
      const id = button.dataset.workId;
      if (expandedWorkIds.has(id)) {
        expandedWorkIds.delete(id);
      } else {
        expandedWorkIds.add(id);
      }
      renderWorks();
    });
  });

  grid.querySelectorAll("[data-video-src]").forEach((button) => {
    button.addEventListener("click", () => openVideoModal(button));
  });

  setupVideoPreviews();
}

updateOverview();
renderExperienceNav();
renderWorks();

const videoModal = document.querySelector("#video-modal");
const videoPlayer = document.querySelector("#video-player");
const videoModalTitle = document.querySelector("#video-modal-title");
const videoModalMeta = document.querySelector("#video-modal-meta");

function openVideoModal(button) {
  if (!videoModal || !videoPlayer) return;

  videoPlayer.src = button.dataset.videoSrc;
  videoModalTitle.textContent = button.dataset.videoTitle || "作品视频";
  videoModalMeta.textContent = button.dataset.videoMeta || "视频预览";
  videoModal.hidden = false;
  document.body.classList.add("modal-open");
  videoPlayer.load();

  const playRequest = videoPlayer.play();
  if (playRequest) {
    playRequest.catch(() => {});
  }
}

function closeVideoModal() {
  if (!videoModal || !videoPlayer) return;

  videoPlayer.pause();
  videoPlayer.removeAttribute("src");
  videoPlayer.load();
  videoModal.hidden = true;
  document.body.classList.remove("modal-open");
}

document.querySelectorAll("[data-close-video]").forEach((button) => {
  button.addEventListener("click", closeVideoModal);
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && videoModal && !videoModal.hidden) {
    closeVideoModal();
  }
});

function setupVideoPreviews() {
  const canHoverPreview = window.matchMedia("(hover: hover) and (pointer: fine)").matches;
  if (!canHoverPreview) return;

  document.querySelectorAll(".preview-media").forEach((video) => {
    const ensurePreviewSource = () => {
      if (video.src || !video.dataset.previewSrc) return;
      video.src = video.dataset.previewSrc;
      video.load();
    };

    const resetToPreviewFrame = () => {
      if (!Number.isFinite(video.duration) || video.duration <= 0) return;
      video.currentTime = Math.min(0.2, video.duration / 4);
    };

    if (video.readyState >= 1) {
      resetToPreviewFrame();
    } else {
      video.addEventListener("loadedmetadata", resetToPreviewFrame, { once: true });
    }

    const previewHost = video.closest(".work-cover, .video-thumb");
    if (!previewHost) return;

    const playPreview = () => {
      ensurePreviewSource();
      video.muted = true;
      video.loop = true;
      const playRequest = video.play();
      if (playRequest) playRequest.catch(() => {});
    };

    const stopPreview = () => {
      video.pause();
      resetToPreviewFrame();
    };

    previewHost.addEventListener("mouseenter", playPreview);
    previewHost.addEventListener("mouseleave", stopPreview);
    previewHost.addEventListener("focusin", playPreview);
    previewHost.addEventListener("focusout", stopPreview);
  });
}
