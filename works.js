function openWorkFromExperience(id) {
  expandedWorkIds.clear();
  expandedWorkIds.add(id);
  renderWorks();

  const target = document.querySelector(`[data-work-card="${id}"]`);
  if (target) {
    target.scrollIntoView({ behavior: "smooth", block: "start" });
  }
}

function renderVideos(work, videos) {
  if (!expandedWorkIds.has(work.id)) return "";
  if (!videos.length) return "";

  return `
    <div class="video-list" aria-label="${work.title}的延展案例列表">
      ${videos.map((video) => `
        <article class="video-card">
          <button
            class="video-thumb"
            type="button"
            data-video-src="${escapeAttribute(video.url)}"
            data-video-poster="${escapeAttribute(video.poster || video.cover || work.cover)}"
            data-video-title="${escapeAttribute(video.title)}"
            data-video-meta="${escapeAttribute(getVideoMeta(video).join(" · "))}"
            aria-label="播放${escapeAttribute(video.title)}"
          >
            ${renderPreviewMedia(video, work.cover, video.title)}
          </button>
          <div class="video-info">
            <div class="video-meta">
              ${getVideoMeta(video).map((item) => `<span>${item}</span>`).join("")}
            </div>
            <h4>${video.title}</h4>
            ${getVideoAction(video)}
          </div>
        </article>
      `).join("")}
    </div>
  `;
}

function renderFeaturedVideo(work, video, secondaryCount) {
  const cover = video?.poster || video?.cover || work.cover;
  if (!video?.url) {
    return `
      ${renderPreviewMedia(video, work.cover || "assets/social-card.png", work.title)}
      <span class="video-count">视频待补充</span>
    `;
  }

  const meta = getVideoMeta(video).join(" · ");
  return `
    ${renderPreviewMedia(video, cover, video.title)}
    <button
      class="feature-video-button"
      type="button"
      data-video-src="${escapeAttribute(video.url)}"
      data-video-poster="${escapeAttribute(video.poster || video.cover || cover)}"
      data-video-title="${escapeAttribute(video.title)}"
      data-video-meta="${escapeAttribute(meta)}"
      aria-label="播放${video.title}"
    >
      <span class="featured-video-label">主推案例</span>
      <span class="featured-video-title">${video.title}</span>
      <span class="featured-video-meta">${meta}</span>
      <span class="featured-play-label">播放主推视频</span>
      <span class="play-indicator large" aria-hidden="true"></span>
    </button>
    <span class="video-count">1 个主推 + ${secondaryCount} 个延展</span>
  `;
}

function renderWorkCard(work) {
  const primaryVideo = getPrimaryVideo(work);
  const secondaryVideos = getSecondaryVideos(work);
  const isExpanded = expandedWorkIds.has(work.id);
  return `
    <article class="work-card ${isExpanded ? "expanded" : ""}" data-work-card="${work.id}">
      <div class="work-cover">
        ${renderFeaturedVideo(work, primaryVideo, secondaryVideos.length)}
      </div>
      <div class="work-body">
        <div class="work-kicker">
          <span>${work.period}</span>
          <span>${work.category}</span>
        </div>
        <h3>${work.title}</h3>
        <p class="company">${work.company}｜${work.position}</p>
        <div class="roles" aria-label="项目职责">${createRoleTags(work.roles)}</div>
        <p class="summary"><span class="case-label">项目内容</span>${work.summary}</p>
        <p class="result"><span class="case-label">核心结果</span>${work.result}</p>
        <div class="video-type-preview" aria-label="视频类型">${createVideoTypeTags(work.videos)}</div>
        ${secondaryVideos.length ? `
          <button class="expand-button" type="button" data-work-id="${work.id}" aria-expanded="${isExpanded}">
            ${isExpanded ? "收起延展案例" : `查看剩余 ${secondaryVideos.length} 条`}
          </button>
        ` : ""}
      </div>
      ${renderVideos(work, secondaryVideos)}
    </article>
  `;
}

function bindWorkInteractions(grid) {
  grid.querySelectorAll(".expand-button").forEach((button) => {
    button.addEventListener("click", () => {
      const id = button.dataset.workId;
      if (expandedWorkIds.has(id)) {
        expandedWorkIds.delete(id);
      } else {
        expandedWorkIds.add(id);
      }
      renderWorks();
      renderExperiments();
    });
  });

  grid.querySelectorAll("[data-video-src]").forEach((button) => {
    button.addEventListener("click", () => openVideoModal(button));
  });
}

function renderWorks() {
  const grid = document.querySelector("#work-grid");
  if (!grid) return;

  grid.innerHTML = getRealProjectWorks().map(renderWorkCard).join("");
  bindWorkInteractions(grid);
}

function renderExperiments() {
  const grid = document.querySelector("#experiment-grid");
  if (!grid) return;

  grid.innerHTML = getExperimentWorks().map(renderWorkCard).join("");
  bindWorkInteractions(grid);
}

